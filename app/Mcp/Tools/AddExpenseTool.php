<?php

namespace App\Mcp\Tools;

use App\Models\Expense;
use Illuminate\Contracts\JsonSchema\JsonSchema;
use Illuminate\JsonSchema\Types\Type;
use Laravel\Mcp\Request;
use Laravel\Mcp\Response;
use Laravel\Mcp\Server\Attributes\Description;
use Laravel\Mcp\Server\Tool;

#[Description('A description of what this tool does.')]
class AddExpenseTool extends Tool
{
    /**
     * Handle the tool request.
     */
    public function handle(Request $request): Response
    {
        $validate = $request->validate([
            'description' => 'required|string',
            'amount' => 'required|numeric',
            'created_at' => 'required|string',
        ]);

        $expense = Expense::create($validate);

        return Response::text('The content generated by the tool.');
    }

    /**
     * Get the tool's input schema.
     *
     * @return array<string, Type>
     */
    public function schema(JsonSchema $schema): array
    {
        return [
            'description' => $schema->string()
                ->description('The description of the tool')
                ->required(),
            'amount' => $schema->number()
                ->description('The amount of the expense')
                ->required(),
            'created_at' => $schema->string()
                ->description('The date and time the expense was created')
                ->required(),
        ];
    }
}
